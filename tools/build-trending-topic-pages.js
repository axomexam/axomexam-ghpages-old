#!/usr/bin/env node
"use strict";

/*
 * tools/build-trending-topic-pages.js
 *
 * Writes the committed HTML page for every trending topic in
 * data/trending-topics/*.json:
 *
 *     topic/trending/<id>/index.html
 *
 * There is no build step at deploy time, so the committed file is what GitHub
 * Pages serves and what a crawler or a JS-less visitor reads. The runtime still
 * fetches the JSON and renders the interactive set; this page carries the same
 * questions as static markup.
 *
 * The page is assembled from the shared shell of a committed trending page
 * (header, footer, asset paths, layout-reserve style), so it stays byte-
 * consistent with the rest of the site. The head, JSON-LD, question list and
 * editorial credit are written from the topic's own JSON.
 *
 * Trending pages are deliberately noindex (see tools/seo-indexing-fix.js) and
 * have no /as/ twin (see SKIP_ROUTES in tools/build-as-twins.js), so this tool
 * touches nothing outside topic/trending/.
 *
 * Idempotent: only pages carrying MARKER are rewritten. A page without the
 * marker is treated as hand-written and is never touched.
 *
 * Usage:
 *   node tools/build-trending-topic-pages.js            # apply
 *   node tools/build-trending-topic-pages.js --check    # report drift only
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const CHECK = process.argv.includes("--check");
const BASE = "https://axomexam.in";
const MARKER = "<!-- generated by tools/build-trending-topic-pages.js -->";
const TRENDING_DIR = path.join(ROOT, "data", "trending-topics");
const TOPIC_DIR = path.join(ROOT, "topic", "trending");
const REF = path.join(TOPIC_DIR, "assam-gk-special", "index.html");

/* ---------- helpers ---------- */

function escapeHtml(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

const loc = (o, lang) => (o == null ? "" : typeof o === "string" ? o : o[lang] || o.en || o.as || "");

/* Question fields are either a bilingual object ({en, as}) or a bare string.
   Option arrays hold one entry per language, and an entry may itself be a
   string or a {en, as} object, so both shapes are accepted. */
function pickEn(v) {
  if (typeof v === "string") return v.trim();
  if (v && typeof v === "object" && typeof v.en === "string") return v.en;
  return "";
}
function pickAs(v) {
  if (typeof v === "string") return v;
  if (v && typeof v === "object" && typeof v.as === "string") return v.as;
  return "";
}

/* Normalise a trending JSON question into { q, a, options, ex } with bilingual
   fields, matching the shape tools/inject-static-questions.js renders. */
function normalizeQuestion(q) {
  if (!q || typeof q !== "object") return null;
  const qEn = pickEn(q.q);
  const qAs = pickAs(q.q);
  if (!qEn) return null;

  const options = [];
  const raw = q.options;
  if (raw && typeof raw === "object" && !Array.isArray(raw)) {
    const en = Array.isArray(raw.en) ? raw.en : [];
    const as = Array.isArray(raw.as) ? raw.as : [];
    for (let i = 0; i < Math.max(en.length, as.length); i++) {
      const oEn = pickEn(en[i]);
      const oAs = pickAs(as[i]);
      if (oEn || oAs) options.push({ en: oEn, as: oAs });
    }
  }

  return {
    q: { en: qEn, as: qAs },
    a: { en: pickEn(q.a), as: pickAs(q.a) },
    options,
    ex: { en: pickEn(q.explanation), as: pickAs(q.explanation) },
  };
}

/* ---------- shared shell (copied from a committed trending page) ---------- */

let SHELL = null;
function shellParts() {
  if (SHELL) return SHELL;
  const s = fs.readFileSync(REF, "utf8");
  const ldS = s.indexOf('<script type="application/ld+json">');
  const ldE = s.indexOf("</script>", ldS) + "</script>".length;
  const mS = s.indexOf('<main id="app"');
  const crS = s.indexOf('<section class="section" data-axo-editorial-credit="1"');
  const crE = s.indexOf("</section>", crS) + "</section>".length;
  SHELL = {
    headPre: s.slice(0, ldS),
    mid: s.slice(ldE, mS),
    credit: s.slice(crS, crE),
    postCredit: s.slice(crE),
  };
  return SHELL;
}

function setHead(preLD, seo) {
  let out = preLD;
  out = out.replace(/<meta name="description" content="[^"]*" \/>/,
    `<meta name="description" content="${escapeHtml(seo.desc)}" />`);
  out = out.replace(/<title>[\s\S]*?<\/title>/, `<title>${escapeHtml(seo.title)}</title>`);
  out = out.replace(/<link rel="canonical" href="[^"]*" \/>/, `<link rel="canonical" href="${seo.url}" />`);
  out = out.replace(/<meta property="og:title" content="[^"]*" \/>/,
    `<meta property="og:title" content="${escapeHtml(seo.title)}" />`);
  out = out.replace(/<meta property="og:description" content="[^"]*" \/>/,
    `<meta property="og:description" content="${escapeHtml(seo.desc)}" />`);
  out = out.replace(/<meta property="og:url" content="[^"]*" \/>/, `<meta property="og:url" content="${seo.url}" />`);
  out = out.replace(/<meta name="twitter:title" content="[^"]*" \/>/,
    `<meta name="twitter:title" content="${escapeHtml(seo.title)}" />`);
  out = out.replace(/<meta name="twitter:description" content="[^"]*" \/>/,
    `<meta name="twitter:description" content="${escapeHtml(seo.desc)}" />`);
  return out;
}

/* ---------- question markup (same shape as tools/inject-static-questions.js) */

const QA_LIST_OPEN = '<div class="qa-list" style="max-width:860px; margin:0 auto;">';

function qaItemHTML(q, n) {
  const parts = [
    `<div lang="en" style="font-weight:800; font-size:1.02rem; line-height:1.5; margin-bottom:6px;">Q${n}. ${escapeHtml(
      q.q.en
    )}</div>`,
  ];
  if (q.q.as) {
    parts.push(
      `<div lang="as" style="color:#64748b; font-size:0.9rem; line-height:1.6; margin-bottom:8px;">${escapeHtml(
        q.q.as
      )}</div>`
    );
  }
  if (q.options.length) {
    const opts = q.options
      .map(
        (o, i) =>
          `<div lang="en" style="margin:2px 0;">(${String.fromCharCode(65 + i)}) ${escapeHtml(o.en)}${
            o.as && o.as !== o.en ? ` <span lang="as" style="color:#64748b;">${escapeHtml(o.as)}</span>` : ""
          }</div>`
      )
      .join("");
    parts.push(`<div style="margin-top:8px; color:#334155;">${opts}</div>`);
  }
  parts.push(`<div lang="en" style="margin-top:8px;"><strong>Answer:</strong> <span>${escapeHtml(q.a.en)}</span></div>`);
  if (q.a.as && q.a.as !== q.a.en) {
    parts.push(`<div lang="as" style="color:#64748b; font-size:0.9rem;">${escapeHtml(q.a.as)}</div>`);
  }
  if (q.ex.en) {
    parts.push(
      `<div lang="en" style="margin-top:6px; font-size:0.9rem; color:#64748b;"><strong>Explanation:</strong> ${escapeHtml(
        q.ex.en
      )}</div>`
    );
  }
  if (q.ex.as) {
    parts.push(`<div lang="as" style="font-size:0.9rem; color:#64748b;">${escapeHtml(q.ex.as)}</div>`);
  }
  return `<div class="qa-item" style="margin-bottom:22px;">${parts.join("")}</div>`;
}

function qaListInnerHTML(qs) {
  const head = `<h2 style="font-size:1.15rem; margin-bottom:18px;">${qs.length} Questions with Answers</h2>`;
  return head + qs.map((q, i) => qaItemHTML(q, i + 1)).join("");
}

/* ---------- JSON-LD (WebPage + Quiz + BreadcrumbList, like the sibling page) */

function truncate(s, n) {
  s = String(s || "");
  return s.length <= n ? s : s.slice(0, n - 1).trimEnd() + "\u2026";
}

function jsonld(topic, qs, url, title, desc, dates) {
  const graph = [
    {
      "@type": "WebPage",
      "@id": `${url}#webpage`,
      url,
      name: `${title} | axomexam`,
      inLanguage: ["en", "as"],
      isPartOf: { "@id": `${BASE}/#website` },
      publisher: { "@id": `${BASE}/#organization` },
      description: desc,
      primaryImageOfPage: { "@type": "ImageObject", url: `${BASE}/og-image.png` },
      breadcrumb: { "@id": `${url}#breadcrumb` },
      mainEntity: { "@id": `${url}#quiz` },
      datePublished: dates.pub,
      dateModified: dates.mod,
      isAccessibleForFree: true,
      speakable: { "@type": "SpeakableSpecification", cssSelector: ["h1", ".page-desc"] },
    },
    {
      "@type": "Quiz",
      "@id": `${url}#quiz`,
      name: `${title} | axomexam`,
      description: desc,
      about: { "@type": "Thing", name: "Trending Topics" },
      educationalAlignment: [
        { "@type": "AlignmentObject", alignmentType: "educationalSubject", targetName: "Trending Topics" },
        { "@type": "AlignmentObject", alignmentType: "educationalLevel", targetName: "Competitive exams" },
      ],
      inLanguage: ["en", "as"],
      hasPart: qs.map((q) => ({
        "@type": "Question",
        eduQuestionType: "Flashcard",
        text: truncate(q.q.en, 300),
        acceptedAnswer: { "@type": "Answer", text: truncate(q.a.en, 500) },
      })),
      datePublished: dates.pub,
      dateModified: dates.mod,
      isAccessibleForFree: true,
      author: { "@id": `${BASE}/#organization` },
      publisher: { "@id": `${BASE}/#organization` },
    },
    {
      "@type": "BreadcrumbList",
      "@id": `${url}#breadcrumb`,
      itemListElement: [
        { "@type": "ListItem", position: 1, name: "Home", item: `${BASE}/` },
        { "@type": "ListItem", position: 2, name: "Trending Topics", item: `${BASE}/trending/` },
      ],
    },
  ];
  return `<script type="application/ld+json">${JSON.stringify({ "@context": "https://schema.org", "@graph": graph })}</script>`;
}

/* ---------- page assembly ---------- */

function buildPage(topic, qs, seo, dates) {
  const shell = shellParts();
  const url = `${BASE}/topic/trending/${topic.id}/`;
  const head = setHead(shell.headPre, { title: seo.title, desc: seo.desc, url });
  const ld = jsonld(topic, qs, url, seo.title, seo.desc, dates);

  const main = `<main id="app" class="container main">
    <noscript>
      <p class="nojs-title"><strong>axomexam - Assam Competitive Exam Preparation Portal</strong></p>
      <p>Free bilingual (Assamese &amp; English) mock tests, previous year solved question papers, and PDF study notes for APSC, Assam Police, ADRE, SSC, and Railway exams.</p>
    </noscript>

      <div class="page-head">
        <nav class="breadcrumb"><a href="/">Home</a><span class="bc-sep">/</span><a href="/trending/">Trending Topics</a><span class="bc-sep">/</span><span>${escapeHtml(seo.name)}</span></nav>
        <h1>${escapeHtml(seo.h1)}</h1>
        <p class="page-desc">${escapeHtml(seo.desc)}</p>
      </div>
<section class="section" style="padding-bottom:40px;">
      ${QA_LIST_OPEN}${qaListInnerHTML(qs)}</div>
    </section>
  </main>`;

  /* The credit section holds one English and one Assamese paragraph, each in
     its own lang-tagged panel. Replace each panel's lead paragraph in turn. */
  let credit = shell.credit;
  for (const panel of [
    { lang: "en", text: seo.credit },
    { lang: "as", text: seo.creditAs },
  ]) {
    const re = new RegExp(
      `(<div lang="${panel.lang}"[^>]*>[\\s\\S]*?<p style="margin:0 0 12px;">)[\\s\\S]*?(</p>)`
    );
    credit = credit.replace(re, `$1${escapeHtml(panel.text)}$2`);
  }
  credit = credit
    .replace(/(Published:<\/strong>|Last updated:<\/strong>)\s*[^<]*/g, (m, label) => `${label} ${dates.en}`)
    .replace(/(প্ৰকাশিত:<\/strong>|শেহতীয়া আপডেট:<\/strong>)\s*[^<]*/g, (m, label) => `${label} ${dates.as}`);

  return `${head}${ld}${shell.mid}${main}\n\n${credit}${shell.postCredit}`.replace(
    "<!DOCTYPE html>",
    `<!DOCTYPE html>\n${MARKER}`
  );
}

/* ---------- main ---------- */

function gitDate(rel) {
  try {
    const out = require("child_process").execFileSync(
      "git", ["log", "-1", "--follow", "--format=%ad", "--date=short", "--", rel],
      { cwd: ROOT, encoding: "utf8" }
    ).trim();
    return out || null;
  } catch (e) { return null; }
}

function fmtDate(iso, lang) {
  if (!iso) return lang === "as" ? "১০ নৱেম্বৰ ২০২৬" : "10 November 2026";
  const d = new Date(iso + "T00:00:00Z");
  const monthsEn = ["January","February","March","April","May","June","July","August","September","October","November","December"];
  const monthsAs = ["জানুৱাৰী","ফেব্ৰুৱাৰী","মাৰ্চ","এপ্ৰিল","মে","জুন","জুলাই","আগষ্ট","ছেপ্তেম্বৰ","অক্টোবৰ","নৱেম্বৰ","ডিচেম্বৰ"];
  if (lang === "as") {
    const asDigits = String(d.getUTCDate()).replace(/\d/g, (x) => "০১২৩৪৫৬৭৮৯"[x]);
    const asYear = String(d.getUTCFullYear()).replace(/\d/g, (x) => "০১২৩৪৫৬৭৮৯"[x]);
    return `${asDigits} ${monthsAs[d.getUTCMonth()]} ${asYear}`;
  }
  return `${d.getUTCDate()} ${monthsEn[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
}

function titleFromTopic(topic) {
  /* "Assam Freedom Fighters: 150 Most Important Questions" -> drop the
     ": N ... Questions" tail so the SEO title can supply its own. */
  const raw = loc(topic.title, "en");
  const short = raw.split(":")[0].trim();
  return short || raw;
}

function main() {
  let files = [];
  try {
    files = fs.readdirSync(TRENDING_DIR).filter((f) => f.endsWith(".json")).sort();
  } catch (e) {
    console.error("build-trending-topic-pages: no data/trending-topics directory");
    process.exit(1);
  }

  let written = 0;
  let current = 0;
  let skipped = 0;
  const report = [];

  for (const f of files) {
    const id = f.replace(/\.json$/, "");
    let d;
    try {
      d = JSON.parse(fs.readFileSync(path.join(TRENDING_DIR, f), "utf8"));
    } catch (e) {
      continue;
    }
    if (!d || !Array.isArray(d.questions)) continue;
    d.id = d.id || id;

    const dest = path.join(TOPIC_DIR, id, "index.html");
    if (fs.existsSync(dest)) {
      const existing = fs.readFileSync(dest, "utf8");
      if (!existing.includes(MARKER)) {
        skipped += 1; /* hand-written page: never touch */
        continue;
      }
    }

    const qs = d.questions.map(normalizeQuestion).filter(Boolean);
    if (!qs.length) continue;

    const shortTitle = titleFromTopic(d);
    const seo = {
      name: shortTitle,
      title: `${shortTitle} Questions with Answers — ADRE, APSC`,
      desc: loc(d.description, "en"),
      h1: loc(d.title, "en"),
      credit: `${loc(d.title, "en")} is a high-demand revision set for Assam competitive exams. The questions are arranged to be read quickly and revised often, and each one is followed by the answer and a plain-language explanation. Facts are checked against standard reference material and publicly available sources, and any correction reported by a reader is reviewed and applied.`,
      creditAs: `${loc(d.title, "as")} অসমৰ প্ৰতিযোগিতামূলক পৰীক্ষাৰ বাবে এটা অতি চাহিদাসম্পন্ন পুনৰালোচনা সংগ্ৰহ। প্ৰতিটো প্ৰশ্ন দ্বিভাষিক আৰু প্ৰতিটো উত্তৰ চমুকৈ ব্যাখ্যা কৰা হৈছে। তথ্য মানক প্ৰসংগ পুথি আৰু বিশ্বাসযোগ্য অনলাইন উৎসৰ সৈতে মিলাই পৰীক্ষা কৰা হয়।`,
    };
    const iso = gitDate(`data/trending-topics/${f}`);
    const today = new Date().toISOString().slice(0, 10);
    const pubIso = iso || today;
    const dates = {
      pub: pubIso,
      mod: pubIso,
      en: fmtDate(pubIso, "en"),
      as: fmtDate(pubIso, "as"),
    };

    const html = buildPage(d, qs, seo, dates);

    if (fs.existsSync(dest) && fs.readFileSync(dest, "utf8") === html) {
      current += 1;
      continue;
    }

    if (!CHECK) {
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.writeFileSync(dest, html, "utf8");
    }
    written += 1;
    report.push(`    ${id}: ${qs.length} questions`);
  }

  console.log(CHECK ? "build-trending-topic-pages: DRIFT CHECK" : "build-trending-topic-pages: applied");
  console.log(`  topics in data/:   ${files.length}`);
  console.log(`  pages written:     ${written}`);
  console.log(`  pages up to date:  ${current}`);
  console.log(`  hand-written kept: ${skipped}`);
  if (report.length) console.log("\n  written:\n" + report.join("\n"));

  if (CHECK && written) process.exitCode = 1;
}

main();
